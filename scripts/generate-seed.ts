// Generates supabase/seed.sql from the bundled Quick Talk content, so the database and
// the offline app never drift apart.
//
//   npm run db:seed:generate      (then `supabase db reset` locally)
//
// Idempotent: every insert is "on conflict do update", keyed by stable slugs.

import { writeFileSync } from "node:fs";
import { categories, replies } from "../src/content/quick-talk.ts";
import { slang } from "../src/content/slang.ts";
import { PLANS } from "../src/lib/plans.ts";
import { tracks } from "../src/content/lessons.ts";

const q = (value: string | null | undefined) => (value == null ? "null" : `'${value.replace(/'/g, "''")}'`);
const json = (value: unknown) => `${q(JSON.stringify(value))}::jsonb`;

const lines: string[] = [
  "-- GENERATED by scripts/generate-seed.ts from src/content (quick-talk, slang, lessons) and src/lib/plans.ts. Do not edit by hand.",
  "begin;",
  "",
  "-- Plans (prices include VAT if applicable)",
  `insert into public.plans (id, name_tr, name_sq, price_eur, interval, features, sort_order) values
  ('monthly', 'Aylık', 'Mujore', ${PLANS[0].priceEur.toFixed(2)}, 'month', ${json({ live: "unlimited", text: "unlimited", lessons: "all", offline: "all" })}, 1),
  ('yearly', 'Yıllık', 'Vjetore', ${PLANS[1].priceEur.toFixed(2)}, 'year', ${json({ live: "unlimited", text: "unlimited", lessons: "all", offline: "all" })}, 2)
on conflict (id) do update set name_tr = excluded.name_tr, name_sq = excluded.name_sq,
  price_eur = excluded.price_eur, interval = excluded.interval, features = excluded.features, sort_order = excluded.sort_order;`,
  "",
];

function expression(slug: string, category: string, tr: string, sq: string) {
  lines.push(
    `insert into public.expressions (slug, category) values (${q(slug)}, ${q(category)})
  on conflict (slug) do update set category = excluded.category;`,
    `insert into public.variants (expression_id, lang, dialect, text)
  select id, 'tr', 'standard', ${q(tr)} from public.expressions where slug = ${q(slug)}
  on conflict (expression_id, lang, dialect) do update set text = excluded.text;`,
    `insert into public.variants (expression_id, lang, dialect, text)
  select id, 'sq', 'standard', ${q(sq)} from public.expressions where slug = ${q(slug)}
  on conflict (expression_id, lang, dialect) do update set text = excluded.text;`,
  );
}

lines.push("-- Reply buttons' expressions");
for (const reply of Object.values(replies)) expression(`reply-${reply.id}`, "reply", reply.tr, reply.sq);

categories.forEach((category, categoryIndex) => {
  lines.push(
    "",
    `-- Category: ${category.slug}`,
    `insert into public.phrase_categories (slug, name_tr, name_sq, icon, sort_order, basic_pack)
  values (${q(category.slug)}, ${q(category.name.tr)}, ${q(category.name.sq)}, ${q(category.icon)}, ${categoryIndex}, ${category.basic})
  on conflict (slug) do update set name_tr = excluded.name_tr, name_sq = excluded.name_sq, icon = excluded.icon,
    sort_order = excluded.sort_order, basic_pack = excluded.basic_pack;`,
  );

  category.phrases.forEach((phrase, phraseIndex) => {
    const slug = `qt-${phrase.id}`;
    expression(slug, category.slug, phrase.tr, phrase.sq);
    lines.push(
      `insert into public.phrases (slug, category_id, expression_id, has_slots, slots, sort_order, offline_pack)
  select ${q(slug)}, c.id, e.id, ${!!phrase.slot}, ${phrase.slot ? json(phrase.slot) : "null"}, ${phraseIndex}, ${q(category.basic ? "basic" : "full")}
  from public.phrase_categories c, public.expressions e where c.slug = ${q(category.slug)} and e.slug = ${q(slug)}
  on conflict (slug) do update set category_id = excluded.category_id, expression_id = excluded.expression_id,
    has_slots = excluded.has_slots, slots = excluded.slots, sort_order = excluded.sort_order, offline_pack = excluded.offline_pack;`,
    );
    (phrase.replies ?? []).forEach((replyId, replyIndex) => {
      lines.push(
        `insert into public.reply_buttons (phrase_id, expression_id, sort_order)
  select p.id, e.id, ${replyIndex} from public.phrases p, public.expressions e
  where p.slug = ${q(slug)} and e.slug = ${q(`reply-${replyId}`)}
  on conflict (phrase_id, expression_id) do update set sort_order = excluded.sort_order;`,
      );
    });
  });
});

lines.push("", "-- Slang & dialect dictionary (src/content/slang.ts)");
for (const entry of slang) {
  const slug = `slang-${entry.slug}`;
  lines.push(
    `insert into public.expressions (slug, category, register, notes_tr, notes_sq)
  values (${q(slug)}, ${q(`slang:${entry.kind}`)}, ${q(entry.register)}, ${q(entry.meaning.tr)}, ${q(entry.meaning.sq)})
  on conflict (slug) do update set category = excluded.category, register = excluded.register,
    notes_tr = excluded.notes_tr, notes_sq = excluded.notes_sq;`,
  );
  const variants: [string, string, string | undefined][] = [
    ["tr", entry.kind === "turkish_slang" ? "turkish_slang" : "standard", entry.tr],
    ["sq", "standard", entry.sqStandard],
    ["sq", "gheg", entry.sqKosovo],
  ];
  for (const [lang, dialect, text] of variants) {
    if (!text) continue;
    lines.push(
      `insert into public.variants (expression_id, lang, dialect, text)
  select id, ${q(lang)}, ${q(dialect)}, ${q(text)} from public.expressions where slug = ${q(slug)}
  on conflict (expression_id, lang, dialect) do update set text = excluded.text;`,
    );
  }
}

lines.push("", "-- Learn Albanian: tracks → units → lessons (src/content/lessons.ts). Exercises are generated in the app.");
tracks.forEach((track, ti) => {
  lines.push(
    `insert into public.courses (slug, title_tr, title_sq, sort_order, is_free) values (${q(track.slug)}, ${q(track.title.tr)}, ${q(track.title.sq)}, ${ti}, true)
  on conflict (slug) do update set title_tr = excluded.title_tr, title_sq = excluded.title_sq, sort_order = excluded.sort_order;`,
  );
  track.units.forEach((unit, ui) => {
    lines.push(
      `insert into public.units (course_id, slug, title_tr, title_sq, sort_order, is_free)
  select id, ${q(unit.slug)}, ${q(unit.title.tr)}, ${q(unit.title.sq)}, ${ui}, ${unit.isFree} from public.courses where slug = ${q(track.slug)}
  on conflict (slug) do update set course_id = excluded.course_id, title_tr = excluded.title_tr, title_sq = excluded.title_sq,
    sort_order = excluded.sort_order, is_free = excluded.is_free;`,
    );
    unit.lessons.forEach((lesson, li) => {
      lines.push(
        `insert into public.lessons (unit_id, slug, title_tr, title_sq, situation, sort_order)
  select id, ${q(lesson.slug)}, ${q(lesson.title.tr)}, ${q(lesson.title.sq)}, ${q(lesson.situation.tr)}, ${li} from public.units where slug = ${q(unit.slug)}
  on conflict (slug) do update set unit_id = excluded.unit_id, title_tr = excluded.title_tr, title_sq = excluded.title_sq,
    situation = excluded.situation, sort_order = excluded.sort_order;`,
      );
    });
  });
});

lines.push("", "commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n"));
console.log(`seed.sql written: ${categories.length} categories, ${categories.reduce((n, c) => n + c.phrases.length, 0)} phrases, ${slang.length} slang entries`);
