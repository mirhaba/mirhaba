// Generates supabase/seed.sql: only the plans (prices from src/lib/plans.ts).
//
//   npm run db:seed:generate      (then `supabase db reset` locally)
//
// Content (Quick Talk, dictionary, lessons) is NOT seeded here any more: the database is its
// source of truth and admins edit it in the dashboard. Starter content is copied in by
// `npm run db:import` / Admin → Import, which never overwrites edits.

import { writeFileSync } from "node:fs";
import { PLANS } from "../src/lib/plans.ts";

const json = (value: unknown) => `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
const features = json({ live: "unlimited", text: "unlimited", lessons: "all", offline: "all" });

const sql = `-- GENERATED by scripts/generate-seed.ts from src/lib/plans.ts. Do not edit by hand.
-- Content is imported separately: npm run db:import (or Admin → Import).
begin;

-- Plans (prices include VAT if applicable)
insert into public.plans (id, name_tr, name_sq, price_eur, interval, features, sort_order) values
  ('monthly', 'Aylık', 'Mujore', ${PLANS[0].priceEur.toFixed(2)}, 'month', ${features}, 1),
  ('yearly', 'Yıllık', 'Vjetore', ${PLANS[1].priceEur.toFixed(2)}, 'year', ${features}, 2)
on conflict (id) do update set name_tr = excluded.name_tr, name_sq = excluded.name_sq,
  price_eur = excluded.price_eur, interval = excluded.interval, features = excluded.features, sort_order = excluded.sort_order;

commit;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("seed.sql written (plans only). Import content with: npm run db:import");
